package org.mcdashboard.history;

import java.util.List;
import java.util.Locale;

/** The few places where SQLite, MySQL/MariaDB and PostgreSQL differ for the history schema. */
public enum SqlDialect {
    SQLITE, MYSQL, POSTGRESQL;

    /** The dialect for a {@code history.storage.type}, or null when it is not a database (or unknown). */
    public static SqlDialect of(String type) {
        if (type == null) return null;
        return switch (type.toLowerCase(Locale.ROOT)) {
            case "sqlite" -> SQLITE;
            case "mysql", "mariadb" -> MYSQL;
            case "postgresql", "postgres" -> POSTGRESQL;
            default -> null;
        };
    }

    /** Column definition of a generated surrogate key that is also the primary key. */
    String identity() {
        return switch (this) {
            case SQLITE -> "INTEGER PRIMARY KEY AUTOINCREMENT";
            case MYSQL -> "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY";
            case POSTGRESQL -> "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
        };
    }

    /**
     * An INSERT that skips a row whose key already exists, and only that: a NOT NULL or foreign key violation still
     * fails. ({@code INSERT OR IGNORE} and MySQL's {@code INSERT IGNORE} would swallow those too.)
     */
    String insertIfAbsent(String table, List<String> columns) {
        String cols = String.join(", ", columns);
        String marks = String.join(", ", columns.stream().map(c -> "?").toList());
        String insert = "INSERT INTO " + table + " (" + cols + ") VALUES (" + marks + ")";
        return switch (this) {
            case SQLITE, POSTGRESQL -> insert + " ON CONFLICT DO NOTHING";
            case MYSQL -> insert + " ON DUPLICATE KEY UPDATE " + columns.get(0) + " = " + columns.get(0);
        };
    }

    /** Integer division: MySQL's {@code /} yields a decimal. */
    String intDiv(String a, long b) {
        return this == MYSQL ? "((" + a + ") DIV " + b + ")" : "((" + a + ") / " + b + ")";
    }

    /** MySQL has no {@code COMMENT ON}: comments are part of the column and table definitions. */
    boolean inlineComments() {
        return this == MYSQL;
    }

    /** PostgreSQL documents tables, columns and constraints with separate {@code COMMENT ON} statements. */
    boolean commentOn() {
        return this == POSTGRESQL;
    }

    /** Appended to every CREATE TABLE. */
    String tableOptions() {
        return this == MYSQL ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4" : "";
    }
}
